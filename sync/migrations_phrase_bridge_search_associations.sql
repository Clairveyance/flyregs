--
-- Data source: 1,012 P/CG terms with a real definition, each run through
-- Claude Sonnet 5 once, asking for the realistic colloquial/informal ways
-- a pilot might phrase that concept instead of the FAA's official term
-- name (e.g. "kill the drone" -> FLIGHT TERMINATION). Cost: $2.27 for all
-- 1,012 terms. Filtered from 4,614 raw generated phrasings down to these
-- 4,291 before insert: excluded 272 that collide with another REAL P/CG
-- term's own name (e.g. "helicopter" was generated as a bridge to
-- ROTORCRAFT, but HELICOPTER is itself a separate, real, independently-
-- defined P/CG term -- confirmed by cross-checking all 4,614 phrasings
-- against all 1,406 real term names, not spot-checked), plus 16 single-
-- word phrasings judged too generic to be a safe bridge target (airport,
-- controller, flying, center, departure, ...).
--
-- Destination: search_term_associations, NOT search_concept_anchors.
-- search_concept_anchors (the hand-curated anchor-boost table) was the
-- obvious first choice -- it's the table that already produces "shows up
-- relevance-sorted with everything else," which is exactly what this
-- needed -- but it was deliberately built to stay small ("Deliberately
-- SMALL and high-traffic," per its own original migration comment) and
-- its matching mechanism (search_anchor_matches/search_phrase_contains) is
-- an unindexed per-row regex evaluated against every candidate row, with
-- no index able to help. Measured directly before touching anything (a
-- rolled-back transaction, zero production risk): inserting this same
-- data there took search_pcg from ~8ms to ~345ms, a real 40x regression.
-- search_term_associations is the RIGHT existing mechanism instead --
-- already live at 10,128 rows with zero performance issues, because
-- expand_search_terms joins on it via a plain btree index (idx_sta_term),
-- an O(log n) lookup regardless of row count. Measured the same way after
-- switching: 3.2ms for the term-expansion step at this data's full scale.
-- It was already feeding search_pcg's exact same out_rank-ranked results
-- through the existing query-expansion pipeline (expandQuery ->
-- expand_search_terms -> searchOtherSources -> search_pcg), so this is
-- genuinely the same "sits in the DB, relevance-sorted with everything
-- else" outcome, just via the mechanism actually built to scale to this.
--
-- Building this exposed a real, separate, pre-existing bug along the way:
-- search_pcg had no exact-title-match bonus at all (unlike search_far/
-- search_aim/search_cfr49, which all score one), so searching a P/CG
-- term by its own exact name could lose to unrelated content whose
-- DEFINITION merely mentioned that same phrase, since search_pcg's body-
-- text-containment bonus scaled UNBOUNDED with occurrence count. Measured
-- corpus-wide against these 697 distinct bridge targets: only 53% (371/
-- 697) returned the correct term as the #1 result before a fix. Fixed
-- separately in migrations_search_pcg_exact_title_match.sql (companion
-- migration, same date) -- 93% (648/697) after.
--
-- score = 1.0 for every row (top of the existing 0.32-1.0 range) --
-- these are curated by an LLM against the FAA's own real definition text,
-- not raw statistical co-occurrence like the existing 10,128 rows, so
-- they should outrank a weaker statistical association for the same
-- input term when both exist.
--
-- Purely additive: ON CONFLICT DO NOTHING, no existing row touched.

